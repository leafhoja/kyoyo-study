def render(key, item):
    title, concept, example, check = item
    section_id = f"textbook-{key}"
    lecture = LECTURES[key].strip() + '\n' + EXTENSIONS[key].strip()
    number = 0
    topics = []
    def identify_heading(match):
        nonlocal number
        number += 1
        topic_id = f"{section_id}-topic-{number}"
        topics.append(f'<li><a href="#{topic_id}">{match.group(1)}</a></li>')
        return f'<h3 id="{topic_id}">{match.group(1)}</h3>'
    lecture = re.sub(r'<h3>(.*?)</h3>', identify_heading, lecture)
    contents = '<details class="textbook-contents"><summary>詳説の項目を開く</summary><ul>' + ''.join(topics) + '</ul></details>'
    return f'''<section class="textbook-addition" aria-labelledby="{section_id}">
<h2 id="{section_id}">詳説　{escape(title)}</h2>
{contents}
{lecture}
<h3 id="{section_id}-review">解法・概念の整理</h3>
<p>{concept}</p>
<div class="box box-ex"><div class="box-head"><span class="box-tag">演習用例</span>手順を追う</div><div class="box-body"><p>{example}</p></div></div>
<h3 id="{section_id}-check">自分で確かめる</h3>
<p>{check}</p>
</section>

'''


def main():
    root = Path(__file__).resolve().parent.parent
    if set(SUPPLEMENTS) != set(LECTURES) or set(SUPPLEMENTS) != set(EXTENSIONS):
        raise ValueError("Lecture and supplement keys differ")
    for key, item in SUPPLEMENTS.items():
        part = "第1部" if int(key.split("-")[0]) <= 4 else "第2部"
        path = root / part / f"ch{key}.html"
        html = path.read_text()
        marker = f'<div id="quiz-container"></div>'
        if marker not in html:
            raise ValueError(f"Quiz marker missing: {path}")
        section_id = f"textbook-{key}"
        existing = re.search(r'<section class="textbook-addition".*?</section>\n\n', html, re.S)
        if existing:
            html = html[:existing.start()] + html[existing.end():]
        quiz_position = html.index(marker)
        heading_position = html.rfind('<h2', 0, quiz_position)
        if heading_position < 0:
            raise ValueError(f"Quiz heading missing: {path}")
        quiz_heading = re.match(r'<h2 id="([^"]+)"', html[heading_position:])
        if quiz_heading is None:
            raise ValueError(f"Quiz heading ID missing: {path}")
        html = html[:heading_position] + render(key, item) + html[heading_position:]
        nav_item = f'    <li><a href="#{section_id}">詳説　{escape(item[0])}</a></li>\n'
        html = re.sub(rf'    <li><a href="#{section_id}">.*?</a></li>\n', '', html, count=1)
        quiz_nav = f'    <li><a href="#{quiz_heading.group(1)}">'
        if quiz_nav not in html:
            raise ValueError(f"Quiz sidebar link missing: {path}")
        html = html.replace(quiz_nav, nav_item + quiz_nav, 1)
        path.write_text(html)
        print(path.relative_to(root))


if __name__ == "__main__":
    main()
